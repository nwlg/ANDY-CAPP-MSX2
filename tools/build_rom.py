#!/usr/bin/env python3
"""Builds the Andy Capp MSX2 ASCII16 MegaROM.

    build_rom.py

Inputs: ../ZX/build/game.bin (the byte-identical reassembly of the tape
image, `make -C ../ZX`), ../ZX/build/game.sym, src/patches.py,
src/runtime.asm, src/rom.asm and the indexed PNGs in assets/.
Output: build/andycapp.rom (16 KiB segments, see doc/DESIGN.md section 4),
plus build/zx_syms.inc, build/tables.inc, build/runtime.sym.
"""
import importlib.util
import os
import subprocess
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ZX = os.path.join(ROOT, '..', 'ZX')
BUILD = os.path.join(ROOT, 'build')
ASSETS = os.path.join(ROOT, 'assets')
SEG = 0x4000
GAME_BASE = 0x5FB4
SEG_GAME = 1

sys.path.insert(0, os.path.join(ROOT, 'tools'))
import import_zx_gfx as gfx  # noqa: E402
import palettes  # noqa: E402


def sjasm(src, out):
    for ext in ('.bin', '.sym', '.lst'):
        p = os.path.join(BUILD, os.path.splitext(out)[0] + ext)
        if os.path.exists(p):
            os.remove(p)
    r = subprocess.run(['sjasm', '-s', src, os.path.join('..', 'build', out)], cwd=os.path.join(ROOT, 'src'),
                       capture_output=True, text=True)
    errs = [l for l in r.stdout.splitlines() if '(' in l and ') :' in l or 'rror' in l]
    if errs or not os.path.exists(os.path.join(BUILD, out)):
        sys.exit('sjasm %s failed:\n%s' % (src, '\n'.join(errs) or r.stdout))


def symbols(path):
    out = {}
    for line in open(path):
        p = line.split()
        if len(p) >= 3 and p[1].lower() == 'equ':
            out[p[0].rstrip(':')] = int(p[2].rstrip('hH'), 16)
    return out


def zx_symbols():
    syms = symbols(os.path.join(ZX, 'build', 'game.sym'))
    lines = ['; Generated by tools/build_rom.py from ../ZX/build/game.sym']
    for name, v in sorted(syms.items(), key=lambda kv: kv[1]):
        lines.append('ZX_%s equ 0x%04X' % (name.replace('.', '_'), v))
    open(os.path.join(BUILD, 'zx_syms.inc'), 'w').write('\n'.join(lines) + '\n')
    return syms


# ---- graphics --------------------------------------------------------------
SIZES = {'opening_screen.png': (512, 424), 'tiles.png': (256, 64), 'sprites_top.png': (256, 128), 'sprites_bot.png': (256, 144),
         'screen.png': (256, 192), 'kiss.png': (32, 8)}


def load_png(name):
    """An asset, checked: indexed PNG, the expected size, colours 0-15 only."""
    path = os.path.join(ASSETS, name)
    im = Image.open(path)
    if im.mode != 'P':
        sys.exit('assets/%s: must be an indexed (palette) PNG, it is %s' % (name, im.mode))
    want = SIZES.get(name, (240, 104) if name.startswith('rooms') else None)
    if want and im.size != want:
        sys.exit('assets/%s: must be %dx%d, it is %dx%d' % (name, want[0], want[1], im.size[0], im.size[1]))
    top = max(im.getdata())
    if top > 15:
        sys.exit('assets/%s: uses colour index %d; only 0-15 exist' % (name, top))
    return im


def mirrored(im):
    return im.transpose(Image.FLIP_LEFT_RIGHT)


def pack_vram():
    """Returns (blobs [(vram address, bytes)], frame table rows, palette bytes)."""
    pages = [Image.new('P', (256, 256), 0) for _ in range(4)]
    mem = gfx.load_memory()
    tops, bots = gfx.part_pairs(mem)
    flags = mem[0xAD9F:0xAD9F + 135]
    top_sheet, bot_sheet = load_png('sprites_top.png'), load_png('sprites_bot.png')

    def cell(sheet, i, w, h):
        return sheet.crop(((i % 8) * w, (i // 8) * h, (i % 8) * w + w, (i // 8) * h + h))

    # tops: page 2 from line 64, 8 per row of 32 lines; left copies then mirrors
    top_cells = []          # (image) in VRAM order
    top_index = {}          # (pair index, facing) -> VRAM slot
    for i, (m, g) in enumerate(tops):
        top_index[(i, 0)] = len(top_cells)
        top_cells.append(cell(top_sheet, i, 32, 32))
    for i, (m, g) in enumerate(tops):
        if flags[g] != 0xFF:
            top_index[(i, 1)] = len(top_cells)
            top_cells.append(mirrored(cell(top_sheet, i, 32, 32)))
        else:
            top_index[(i, 1)] = top_index[(i, 0)]
    bot_cells = []
    bot_index = {}
    for i, (m, g) in enumerate(bots):
        bot_index[(i, 0)] = len(bot_cells)
        bot_cells.append(cell(bot_sheet, i, 32, 24))
    for i, (m, g) in enumerate(bots):
        if flags[g] != 0xFF:
            bot_index[(i, 1)] = len(bot_cells)
            bot_cells.append(mirrored(cell(bot_sheet, i, 32, 24)))
        else:
            bot_index[(i, 1)] = bot_index[(i, 0)]
    assert len(top_cells) <= 48, 'too many top halves for VRAM'
    assert len(bot_cells) <= 88, 'too many bottom halves for VRAM'

    def top_pos(slot):
        return (slot % 8) * 32, 576 + (slot // 8) * 32

    def bot_pos(slot):
        if slot < 80:
            return (slot % 8) * 32, 768 + (slot // 8) * 24
        return (slot - 80) * 32, 212

    def put(img, x, y):
        pages[y // 256].paste(img, (x, y % 256))

    for s, im in enumerate(top_cells):
        put(im, *top_pos(s))
    for s, im in enumerate(bot_cells):
        put(im, *bot_pos(s))
    put(load_png('tiles.png'), 0, 512)
    put(load_png('screen.png'), 0, 10)
    put(load_png('kiss.png'), 144, 496)

    # frame table: per frame and facing, top x, top y, bottom x, bottom y
    word = gfx.word
    rows = []
    for f in range(gfx.NUM_FRAMES):
        t, b = word(mem, gfx.TOP_TABLE + 2 * f), word(mem, gfx.BOTTOM_TABLE + 2 * f)
        ti, bi = tops.index((t & 255, t >> 8)), bots.index((b & 255, b >> 8))
        for facing in (0, 1):
            tx, ty = top_pos(top_index[(ti, facing)])
            bx, by = bot_pos(bot_index[(bi, facing)])
            rows.append((f, facing, tx, ty, bx, by))

    def blob(page, y0, y1):
        im = pages[page]
        px = im.load()
        data = bytearray()
        for y in range(y0, y1):
            for x in range(0, 256, 2):
                data.append((px[x, y] & 15) << 4 | (px[x + 1, y] & 15))
        return (page * 256 + y0) * 128, bytes(data)

    blobs = [blob(0, 10, 202), blob(0, 212, 236), blob(1, 240, 248), blob(2, 0, 256), blob(3, 0, 240)]
    return blobs, rows


def rle(data):
    """00h-7Fh: n+1 literal bytes follow; 80h-FFh: the next byte n-7Dh times."""
    out = bytearray()
    lit = bytearray()
    i = 0
    while i < len(data):
        n = 1
        while i + n < len(data) and data[i + n] == data[i] and n < 130:
            n += 1
        if n >= 3:
            while lit:
                out += bytes([min(len(lit), 128) - 1]) + lit[:128]
                lit = lit[128:]
            out += bytes([0x7D + n, data[i]])
            i += n
        else:
            lit.append(data[i])
            i += 1
    while lit:
        out += bytes([min(len(lit), 128) - 1]) + lit[:128]
        lit = lit[128:]
    return bytes(out)


def room_streams():
    """RLE stream of every room picture (104 full VRAM lines, the play area at
    x 8-247) and the picture of each room."""
    names = {}
    for line in open(os.path.join(ASSETS, 'rooms', 'rooms.txt')):
        if ':' in line and not line.startswith('#'):
            r, n = line.split(':')
            names[int(r)] = n.strip()
    streams = {}
    for n in sorted(set(names.values())):
        im = load_png(os.path.join('rooms', n + '.png'))
        assert im.size == (240, 104), n
        px = im.load()
        data = bytearray()
        for y in range(104):
            row = [0] * 8 + [px[x, y] & 15 for x in range(240)] + [0] * 8
            for x in range(0, 256, 2):
                data.append(row[x] << 4 | row[x + 1])
        streams[n] = rle(bytes(data))
    return streams, [names[r] for r in range(80)]


# ---- boot pictures ----------------------------------------------------------
def logo():
    """assets/dihalt_logo.png (any size, RGB) scaled to 256 x 212 in its own
    16 colours of the V9938 (the most used colours that are clearly
    different from each other, every pixel to the nearest)."""
    im = Image.open(os.path.join(ASSETS, 'dihalt_logo.png')).convert('RGB').resize((256, 212), Image.LANCZOS)
    src = im.load()
    snap = [[tuple((v * 7 + 127) // 255 for v in src[x, y]) for x in range(256)] for y in range(212)]
    count = {}
    for row in snap:
        for c in row:
            count[c] = count.get(c, 0) + 1
    ranked = [c for c, _ in sorted(count.items(), key=lambda kv: -kv[1])]
    pal = []
    for far in (12, 6, 3, 1):
        for c in ranked:
            if len(pal) < 16 and all(sum((a - b) ** 2 for a, b in zip(c, q)) >= far for q in pal):
                pal.append(c)
    pal += [(0, 0, 0)] * (16 - len(pal))
    near = {}

    def nearest(c):
        if c not in near:
            near[c] = min(range(16), key=lambda i: sum((a - b) ** 2 for a, b in zip(c, pal[i])))
        return near[c]
    idx = [[nearest(c) for c in row] for row in snap]
    data = bytearray()
    for y in range(212):
        for x in range(0, 256, 2):
            data.append(idx[y][x] << 4 | idx[y][x + 1])
    return bytes(data), palettes.msx(pal), idx[0][0]


def opening():
    """assets/opening_screen.png (512 x 424, own palette): field 0 = even
    lines to SCREEN 7 page 0, field 1 = odd lines to page 1."""
    im = load_png('opening_screen.png')
    px = im.load()
    blobs = []
    for field in (0, 1):
        rows = bytearray()
        for y in range(field, 424, 2):
            for x in range(0, 512, 2):
                rows.append((px[x, y] & 15) << 4 | (px[x + 1, y] & 15))
        blobs.append((0x10000 * field, bytes(rows)))
    p = im.getpalette()[:48]
    pal = [tuple((v * 7 + 127) // 255 for v in p[3 * i:3 * i + 3]) for i in range(16)]
    return blobs, palettes.msx(pal)


# ---- patches ------------------------------------------------------------------
def load_patches():
    spec = importlib.util.spec_from_file_location('patches', os.path.join(ROOT, 'src', 'patches.py'))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.PATCHES


def apply_patches(image, rt):
    image = bytearray(image)
    for addr, expect, repl, why in load_patches():
        exp = bytes.fromhex(expect)
        o = addr - GAME_BASE
        if image[o:o + len(exp)] != exp:
            sys.exit('patch %04X (%s): expected %s, found %s' % (addr, why, expect, image[o:o + len(exp)].hex(' ')))
        if isinstance(repl, tuple):
            op, name = repl
            v = rt[name]
            new = bytes([{'jp': 0xC3, 'call': 0xCD}[op], v & 255, v >> 8])
        else:
            text = repl
            for name, v in rt.items():
                text = text.replace('{%s}' % name, '%02x %02x' % (v & 255, v >> 8))
            new = bytes.fromhex(text)
        assert len(new) <= len(exp), 'patch %04X longer than the bytes it replaces' % addr
        image[o:o + len(exp)] = new + bytes(len(exp) - len(new))
    return image


def rescale_periods(image, syms):
    """Note periods for the 1.7898 MHz MSX PSG (the 128K AY runs at 1.7734 MHz)."""
    base = syms['PeriodTable'] - GAME_BASE
    for i in range(82):
        o = base + 2 * i
        p = image[o] | image[o + 1] << 8
        q = min(0xFFF, round(p * 1789772.5 / 1773400.0))
        image[o], image[o + 1] = q & 255, q >> 8
    return image


def main():
    os.makedirs(BUILD, exist_ok=True)
    game = open(os.path.join(ZX, 'build', 'game.bin'), 'rb').read()
    orig = open(os.path.join(ZX, 'orig', 'game_5FB4_FEFF.bin'), 'rb').read()
    assert game == orig, '../ZX/build/game.bin differs from the tape bytes: run make -C ../ZX'
    syms = zx_symbols()
    blobs, rows = pack_vram()
    streams, room_names = room_streams()

    # ROM layout: segment 0 boot + runtime, then the game image, then the blobs
    nseg_game = (len(game) + SEG - 1) // SEG
    chunks = []
    o = 0
    while o < len(game):
        dest = GAME_BASE + o
        n = min(len(game) - o, SEG - o % SEG, 0x4000 - dest % 0x4000)
        chunks.append((SEG_GAME + o // SEG, o % SEG, dest, n))
        o += n
    blob_rom = bytearray()
    blob_entries = []
    seg0 = SEG_GAME + nseg_game
    for vaddr, data in blobs:
        o = 0
        while o < len(data):
            pos = len(blob_rom)
            n = min(len(data) - o, SEG - pos % SEG)
            blob_entries.append((seg0 + pos // SEG, pos % SEG, vaddr + o, n))
            blob_rom += data[o:o + n]
            o += n
    room_rom = bytearray()
    room_pos = {}
    seg_rooms = seg0 + (len(blob_rom) + SEG - 1) // SEG
    for n, data in streams.items():
        if len(room_rom) % SEG + len(data) > SEG:
            room_rom += b'\xFF' * (SEG - len(room_rom) % SEG)
        room_pos[n] = (seg_rooms + len(room_rom) // SEG, len(room_rom) % SEG)
        room_rom += data
    # logo and opening, after the rooms
    logo_data, logo_pal, logo_border = logo()
    open_blobs, open_pal = opening()
    boot_rom = bytearray()
    seg_boot = seg_rooms + (len(room_rom) + SEG - 1) // SEG

    def place(blist):
        entries = []
        for vaddr, data in blist:
            o = 0
            while o < len(data):
                pos = len(boot_rom)
                n = min(len(data) - o, SEG - pos % SEG)
                entries.append((seg_boot + pos // SEG, pos % SEG, vaddr + o, n))
                boot_rom.extend(data[o:o + n])
                o += n
        return entries
    logo_entries = place([(0, logo_data)])
    open_entries = place(open_blobs)
    inc = ['; Generated by tools/build_rom.py', 'rt_game_chunks:   ; segment, offset, destination, length']
    for s, off, dest, n in chunks:
        inc.append('        db %d\n        dw 0x%04X, 0x%04X, %d' % (s, off, dest, n))
    inc.append('        db 0xFF')
    for label, entries in (('rt_vram_blobs', blob_entries), ('rt_logo_blobs', logo_entries),
                           ('rt_opening_blobs', open_entries)):
        inc.append(label + ':    ; segment, offset, VRAM address bits 0-15, bit 16, length')
        for sg, off, v, n in entries:
            inc.append('        db %d\n        dw 0x%04X, 0x%04X\n        db %d\n        dw %d' % (sg, off, v & 0xFFFF, v >> 16, n))
        inc.append('        db 0xFF')
    inc.append('rt_logo_palette:')
    inc.append('        db ' + ','.join('0x%02X' % b for b in logo_pal))
    inc.append('LOGO_BORDER equ %d' % logo_border)
    inc.append('rt_opening_palette:')
    inc.append('        db ' + ','.join('0x%02X' % b for b in open_pal))
    for label, pal in (('rt_pal_day', palettes.variant('day')), ('rt_pal_dusk', palettes.variant('dusk')),
                       ('rt_pal_night', palettes.variant('night')), ('rt_pal_hud_rom', palettes.HUD)):
        inc.append(label + ':')
        inc.append('        db ' + ','.join('0x%02X' % b for b in palettes.msx(pal)))
    inc.append('rt_rooms:         ; per room: segment, offset of its background stream')
    for r, n in enumerate(room_names):
        inc.append('        db %d\n        dw 0x%04X   ; room %d: %s' % (room_pos[n][0], room_pos[n][1], r, n))
    inc.append('rt_frame_src:     ; per frame and facing: top x, top y, bottom x, bottom y')
    for f, facing, tx, ty, bx, by in rows:
        inc.append('        db %d\n        dw %d\n        db %d\n        dw %d   ; frame %d facing %d' % (tx, ty, bx, by, f, facing))
    open(os.path.join(BUILD, 'tables.inc'), 'w').write('\n'.join(inc) + '\n')

    sjasm('runtime.asm', 'runtime.bin')
    rt = symbols(os.path.join(BUILD, 'runtime.sym'))
    sjasm('rom.asm', 'boot.bin')
    boot = open(os.path.join(BUILD, 'boot.bin'), 'rb').read()
    assert len(boot) <= SEG

    image = apply_patches(game, rt)
    image = rescale_periods(image, syms)
    rom = bytearray(boot + b'\xFF' * (SEG - len(boot)))
    rom += image + b'\xFF' * (nseg_game * SEG - len(image))
    rom += blob_rom
    rom += b'\xFF' * (-len(rom) % SEG)
    rom += room_rom
    rom += b'\xFF' * (-len(rom) % SEG)
    rom += boot_rom
    rom += b'\xFF' * (-len(rom) % SEG)
    while len(rom) & (len(rom) - 1):           # a power of two for the mappers' sake
        rom += b'\xFF' * SEG
    open(os.path.join(BUILD, 'andycapp.rom'), 'wb').write(rom)
    print('build/andycapp.rom: %d KiB, runtime %d bytes, %d VRAM blob bytes, %d room pictures in %d bytes' % (
        len(rom) // 1024, rt.get('rt_end', 0), len(blob_rom), len(streams), sum(map(len, streams.values()))))


if __name__ == '__main__':
    main()
